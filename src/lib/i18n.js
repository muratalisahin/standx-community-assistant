export function langById(id) {
  return LANGS.find((l) => l.id === id) || LANGS[1];
}

export function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (LANGS.some((l) => l.id === saved)) return saved;
  } catch {
    /* ignore */
  }
  const n = String(navigator.language || "en").toLowerCase();
  if (n.startsWith("tr")) return "tr";
  if (n.startsWith("fr")) return "fr";
  if (n.startsWith("zh")) return "zh";
  if (n.startsWith("ja")) return "ja";
  return "en";
}

export function saveLang(id) {
  try {
    localStorage.setItem(LANG_KEY, id);
  } catch {
    /* ignore */
  }
}
